  pdf.text('Fleet Forensic Engineering Audit | Menu Karachi Office', margin + 30, 10);

  pdf.setDrawColor(...BORDER_LIGHT);
  pdf.setLineWidth(0.3);
  pdf.line(margin, 12, pageWidth - margin, 12);

  // Running Footer
  pdf.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);
  pdf.setFontSize(7.5);
  pdf.setTextColor(...TEXT_MUTED);
  pdf.text('Confidential - Generated by POWER2G Diagnostics & SolisCloud Telemetry Engine', margin, pageHeight - 8);
  pdf.text(`Page ${pageNum} of ${totalPages}`, pageWidth - margin - 18, pageHeight - 8);
